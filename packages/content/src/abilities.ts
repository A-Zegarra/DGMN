export function getAbilitiesForSpecies(speciesId: string): Ability[] {
  const ids = SPECIES_ABILITIES[speciesId] ?? GENERIC_IDS;
  return ids
    .map((id) => ABILITIES[id])
    .filter((ability): ability is Ability => Boolean(ability));
}
